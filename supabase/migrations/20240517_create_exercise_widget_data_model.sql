-- 1. Create workout_sessions table
CREATE TABLE public.workout_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  date DATE NOT NULL,
  duration INT,
  notes TEXT,
  perceived_difficulty INT,
  type TEXT NOT NULL CHECK (type IN ('strength', 'cardio', 'mixed')),
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

COMMENT ON TABLE public.workout_sessions IS 'Represents a single workout event for a user.';
COMMENT ON COLUMN public.workout_sessions.user_id IS 'Foreign key referencing the user.';
COMMENT ON COLUMN public.workout_sessions.perceived_difficulty IS 'User-reported difficulty (e.g., RPE scale).';
COMMENT ON COLUMN public.workout_sessions.type IS 'Type of workout: strength, cardio, or mixed.';

-- 2. Create exercises table (catalog)
CREATE TABLE public.exercises (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('strength', 'cardio')),
  default_unit TEXT,
  description TEXT,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

COMMENT ON TABLE public.exercises IS 'Catalog of exercise types.';
COMMENT ON COLUMN public.exercises.category IS 'Exercise category: strength or cardio.';

-- 3. Create workout_exercises table (join session <-> exercise)
CREATE TABLE public.workout_exercises (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES public.workout_sessions(id) ON DELETE CASCADE,
  exercise_id BIGINT NOT NULL REFERENCES public.exercises(id),
  "order" INT,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

COMMENT ON TABLE public.workout_exercises IS 'Exercises performed in a workout session.';

-- 4. Create sets table (for strength exercises)
CREATE TABLE public.sets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workout_exercise_id BIGINT NOT NULL REFERENCES public.workout_exercises(id) ON DELETE CASCADE,
  set_number INT NOT NULL,
  reps INT,
  weight NUMERIC,
  rir INT, -- Reps in reserve
  tempo TEXT,
  rest_seconds INT,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

COMMENT ON TABLE public.sets IS 'Tracks sets for strength exercises.';

-- 5. Create cardio_metrics table (for cardio exercises)
CREATE TABLE public.cardio_metrics (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workout_exercise_id BIGINT NOT NULL REFERENCES public.workout_exercises(id) ON DELETE CASCADE,
  distance NUMERIC,
  duration INT,
  calories INT,
  avg_hr INT,
  max_hr INT,
  intensity TEXT,
  pace NUMERIC,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

COMMENT ON TABLE public.cardio_metrics IS 'Metrics for cardio exercises.';

-- 6. Create exercise_tags table
CREATE TABLE public.exercise_tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exercise_id BIGINT NOT NULL REFERENCES public.exercises(id) ON DELETE CASCADE,
  tag TEXT NOT NULL
);

COMMENT ON TABLE public.exercise_tags IS 'Tags for exercises (e.g., muscle group, equipment).';

