-- 5. Create a function to update the updated_at timestamp
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 6. Create a trigger to call the function before any update
CREATE TRIGGER on_dashboard_layouts_updated
BEFORE UPDATE ON public.dashboard_layouts
FOR EACH ROW
EXECUTE FUNCTION public.handle_updated_at();

-- 7. Optional: Add an index for faster lookups by user_id
CREATE INDEX idx_dashboard_layouts_user_id ON public.dashboard_layouts(user_id);

