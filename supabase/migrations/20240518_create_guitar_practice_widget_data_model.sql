-- 1. Practice Sessions
CREATE TABLE public.guitar_practice_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  date DATE NOT NULL,
  duration INT,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);
COMMENT ON TABLE public.guitar_practice_sessions IS 'Represents a single guitar practice session.';

-- 2. Techniques Catalog
CREATE TABLE public.guitar_techniques (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT,
  difficulty_level TEXT,
  description TEXT,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);
COMMENT ON TABLE public.guitar_techniques IS 'Catalog of guitar techniques (e.g., alternate picking, sweep picking, chords).';

-- 3. Songs/Pieces Catalog
CREATE TABLE public.guitar_songs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  artist TEXT,
  difficulty_level TEXT,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);
COMMENT ON TABLE public.guitar_songs IS 'Catalog of songs or pieces practiced.';

-- 4. Skills Catalog
CREATE TABLE public.guitar_skills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT,
  description TEXT,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);
COMMENT ON TABLE public.guitar_skills IS 'Catalog of skill categories (e.g., rhythm, lead, improvisation).';

-- 5. Join Table: Techniques practiced in a session
CREATE TABLE public.guitar_session_techniques (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES public.guitar_practice_sessions(id) ON DELETE CASCADE,
  technique_id BIGINT NOT NULL REFERENCES public.guitar_techniques(id),
  skill_id BIGINT REFERENCES public.guitar_skills(id),
  notes TEXT,
  duration INT,
  proficiency_level TEXT,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);
COMMENT ON TABLE public.guitar_session_techniques IS 'Techniques practiced in a session, with optional skill and proficiency.';

-- 6. Join Table: Songs practiced in a session
