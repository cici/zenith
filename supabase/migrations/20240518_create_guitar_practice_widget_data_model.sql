-- RLS for guitar_practice_sessions
CREATE POLICY "Allow users to select their own practice sessions"
  ON public.guitar_practice_sessions
  FOR SELECT
  USING (auth.uid() = user_id);

CREATE POLICY "Allow users to insert their own practice sessions"
  ON public.guitar_practice_sessions
  FOR INSERT
  WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Allow users to update their own practice sessions"
  ON public.guitar_practice_sessions
  FOR UPDATE
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

